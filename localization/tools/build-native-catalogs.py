"""Deterministic exact-message import; fuzzy/plural/ambiguous translations excluded."""
import argparse, ast, json, re
from pathlib import Path
root = Path(__file__).resolve().parents[2]
base = root / 'localization'

def catalog(path):
    values = {}; entry = {}; field = None; fuzzy = False
    def finish():
        if not fuzzy and entry.get('msgid') and entry.get('msgstr') and 'msgid_plural' not in entry:
            values.setdefault(entry['msgid'], set()).add(entry['msgstr'])
    for line in path.read_text(encoding='utf-8-sig').splitlines() + ['']:
        if not line.strip():
            finish(); entry = {}; field = None; fuzzy = False
        elif line.startswith('#,') and 'fuzzy' in line.split(','): fuzzy = True
        elif line.startswith('#,') and 'fuzzy' in line: fuzzy = True
        elif line.startswith('#'): continue
        elif (match := re.match(r'^(msgctxt|msgid_plural|msgid|msgstr)\s+(".*")$', line)):
            field = match[1]; entry[field] = ast.literal_eval(match[2])
        elif line.startswith('msgstr['): field = None; entry['msgid_plural'] = 'plural'
        elif line.startswith('"') and field: entry[field] += ast.literal_eval(line)
    return {key: next(iter(v)) for key, v in values.items() if len(v) == 1}

def outputs():
    keys = set()
    pattern = r'(?:Text|Button|Toggle|Picker|Menu|Label|TextField|flag|readingOption|NSLocalizedString|accessibilityLabel|navigationTitle)\("([^"\\\n]+)"'
    for path in sorted((root/'platforms/macos').glob('*.swift')):
        keys.update(re.findall(pattern, path.read_text()))
    result = {}; coverage = {}
    for lang in ['en','fr','de','es']:
        imported = {} if lang == 'en' else catalog(base/'gettext'/f'{lang}.po')
        override = base/'overrides'/f'{lang}.json'
        if override.exists(): imported.update(json.loads(override.read_text()))
        translated = {key: (key if lang == 'en' else imported[key]) for key in sorted(keys) if lang == 'en' or key in imported}
        header = '// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by localization/tools/build-native-catalogs.py; edit gettext/overrides, not this file.\n'
        text = header + ''.join(json.dumps(k,ensure_ascii=False)+' = '+json.dumps(v,ensure_ascii=False)+';\n' for k,v in translated.items())
        result[base/'macos'/f'{lang}.lproj'/'Localizable.strings'] = text
        coverage[lang] = {'translated_or_fallback_entries':len(translated),'extracted_literal_keys':len(keys),'partial':lang != 'en'}
    result[base/'coverage.json'] = json.dumps(coverage, indent=2)+'\n'
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    mismatches=[]
    for path,text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text: mismatches.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True); path.write_text(text)
    if mismatches: raise SystemExit('Regenerate native catalogs: '+', '.join(mismatches))
    print('Native catalogs current' if args.check else 'Native catalogs regenerated from literal keys, reviewed overrides and exact gettext matches')
